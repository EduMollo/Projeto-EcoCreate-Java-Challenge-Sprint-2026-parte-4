CREATE TABLE clyvovet.aud_pet (
 id_auditoria bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_registro bigint NOT NULL, tipo_operacao varchar(10) NOT NULL,
 nome_usuario text NOT NULL, data_hora timestamptz NOT NULL DEFAULT current_timestamp,
 valor_anterior jsonb, valor_novo jsonb);
CREATE INDEX ix_aud_pet_registro ON clyvovet.aud_pet(id_registro, data_hora);

CREATE FUNCTION clyvovet.auditar_pet() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
BEGIN
 INSERT INTO clyvovet.aud_pet(id_registro,tipo_operacao,nome_usuario,valor_anterior,valor_novo)
 VALUES(CASE WHEN TG_OP='DELETE' THEN OLD.id ELSE NEW.id END,TG_OP,current_user,
 CASE WHEN TG_OP<>'INSERT' THEN jsonb_build_object('id',OLD.id,'nome',OLD.nome,'peso_kg',OLD.peso_kg) END,
 CASE WHEN TG_OP<>'DELETE' THEN jsonb_build_object('id',NEW.id,'nome',NEW.nome,'peso_kg',NEW.peso_kg) END);
 RETURN NULL; -- trigger AFTER
END;
$$;
CREATE TRIGGER trg_aud_pet AFTER INSERT OR UPDATE OR DELETE ON clyvovet.tb_pet
 FOR EACH ROW EXECUTE FUNCTION clyvovet.auditar_pet();

CREATE FUNCTION clyvovet.exportar_atendimentos(p_clinica bigint DEFAULT NULL) RETURNS text
LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE resultado text;
BEGIN
 IF p_clinica IS NOT NULL AND (p_clinica<=0 OR NOT EXISTS(SELECT 1 FROM clyvovet.tb_clinica WHERE id=p_clinica)) THEN
  RAISE EXCEPTION 'Clinica invalida' USING ERRCODE='22023';
 END IF;
 SELECT coalesce(jsonb_agg(jsonb_build_object(
  'id_atendimento',a.id,'data',to_char(a.data_consulta,'YYYY-MM-DD'),
  'clinica',c.nome,'veterinario',a.veterinario,'servico',a.tipo_consulta,
  'valor',a.valor,'status',a.status,
  'pet',jsonb_build_object('id',p.id,'nome',p.nome,'especie',p.especie),
  'tutor',jsonb_build_object('id',t.id,'nome',t.nome)) ORDER BY a.id),'[]'::jsonb)::text
 INTO resultado FROM clyvovet.tb_consulta a
 JOIN clyvovet.tb_clinica c ON c.id=a.id_clinica
 JOIN clyvovet.tb_pet p ON p.id=a.id_pet
 JOIN clyvovet.tb_tutor t ON t.id=p.id_tutor
 WHERE p_clinica IS NULL OR a.id_clinica=p_clinica;
 RETURN resultado;
END;
$$;

CREATE FUNCTION clyvovet.faturamento_anual(p_ano integer) RETURNS text
LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE r record; total numeric:=0; subtotal numeric:=0; clinica bigint; resultado text;
BEGIN
 IF p_ano IS NULL OR p_ano<2000 OR p_ano>2100 THEN
  RAISE EXCEPTION 'Ano invalido' USING ERRCODE='22023';
 END IF;
 resultado:='Faturamento '||p_ano||chr(10);
 FOR r IN SELECT a.id_clinica,c.nome,a.tipo_consulta,a.valor FROM clyvovet.tb_consulta a
 JOIN clyvovet.tb_clinica c ON c.id=a.id_clinica
 WHERE a.status='CONCLUIDA' AND a.data_consulta>=make_date(p_ano,1,1)
 AND a.data_consulta<make_date(p_ano+1,1,1)
 ORDER BY a.id_clinica,a.tipo_consulta,a.id LOOP
  IF clinica IS DISTINCT FROM r.id_clinica THEN
   IF clinica IS NOT NULL THEN resultado:=resultado||'Subtotal: '||to_char(subtotal,'FM9999999990.00')||chr(10); END IF;
   clinica:=r.id_clinica; subtotal:=0; resultado:=resultado||r.nome||chr(10);
  END IF;
  subtotal:=subtotal+coalesce(r.valor,0); total:=total+coalesce(r.valor,0);
  resultado:=resultado||'  '||r.tipo_consulta||': '||to_char(coalesce(r.valor,0),'FM9999999990.00')||chr(10);
 END LOOP;
 IF clinica IS NOT NULL THEN resultado:=resultado||'Subtotal: '||to_char(subtotal,'FM9999999990.00')||chr(10); END IF;
 RETURN resultado||'Total: '||to_char(total,'FM9999999990.00');
END;
$$;
