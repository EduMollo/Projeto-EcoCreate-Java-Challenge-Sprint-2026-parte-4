create table tb_perfil (
    id number(19) generated by default as identity,
    descricao varchar2(20) not null,
    primary key (id)
);

create table tb_usuario (
    id number(19) generated by default as identity,
    username varchar2(60) not null,
    senha varchar2(100) not null,
    nome_exibicao varchar2(100) not null,
    ativo number(1) default 1 not null,
    data_criacao date not null,
    id_tutor number(19),
    primary key (id)
);

create table tb_usuario_perfil (
    id_usuario number(19) not null,
    id_perfil number(19) not null,
    primary key (id_usuario, id_perfil)
);

create table tb_tutor (
    id number(19) generated by default as identity,
    nome varchar2(100) not null,
    cpf varchar2(11) not null,
    email varchar2(150) not null,
    telefone varchar2(11) not null,
    data_nascimento date not null,
    ativo number(1) default 1 not null,
    primary key (id)
);

create table tb_clinica (
    id number(19) generated by default as identity,
    nome varchar2(150) not null,
    cnpj varchar2(14) not null,
    telefone varchar2(11) not null,
    email varchar2(150) not null,
    endereco varchar2(300) not null,
    cidade varchar2(100) not null,
    estado varchar2(2) not null,
    ativo number(1) default 1 not null,
    primary key (id)
);

create table tb_pet (
    id number(19) generated by default as identity,
    nome varchar2(80) not null,
    especie varchar2(20) not null,
    raca varchar2(80) not null,
    data_nascimento date not null,
    peso_kg number(6,2),
    sexo varchar2(10),
    castrado number(1),
    microchip varchar2(20),
    observacoes varchar2(500),
    ativo number(1) default 1 not null,
    id_tutor number(19) not null,
    id_clinica_principal number(19),
    primary key (id)
);

create table tb_consulta (
    id number(19) generated by default as identity,
    data_consulta date not null,
    status varchar2(20) not null,
    tipo_consulta varchar2(30) not null,
    veterinario varchar2(100) not null,
    diagnostico varchar2(1000),
    prescricao varchar2(1000),
    observacoes varchar2(500),
    valor number(10,2),
    data_retorno date,
    criado_em timestamp not null,
    id_pet number(19) not null,
    id_clinica number(19) not null,
    primary key (id)
);

create table tb_evento_saude (
    id number(19) generated by default as identity,
    tipo_evento varchar2(30) not null,
    descricao varchar2(500) not null,
    data_evento date not null,
    data_proxima_acao date,
    concluido number(1) default 0 not null,
    criado_em timestamp not null,
    id_pet number(19) not null,
    id_consulta number(19),
    primary key (id)
);

create table tb_vacina (
    id number(19) generated by default as identity,
    nome varchar2(100) not null,
    fabricante varchar2(100) not null,
    lote varchar2(50),
    data_aplicacao date not null,
    data_validade date not null,
    proxima_dose date,
    criado_em timestamp not null,
    id_pet number(19) not null,
    id_clinica number(19),
    primary key (id)
);

create table tb_medicamento (
    id number(19) generated by default as identity,
    nome varchar2(100) not null,
    principio_ativo varchar2(100),
    dosagem varchar2(100) not null,
    frequencia varchar2(100) not null,
    data_inicio date not null,
    data_fim date,
    uso_continuo number(1) default 0 not null,
    observacoes varchar2(500),
    id_pet number(19) not null,
    id_consulta number(19),
    primary key (id)
);
