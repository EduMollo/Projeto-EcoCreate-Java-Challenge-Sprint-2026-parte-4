CREATE OR REPLACE VIEW CLINICA AS SELECT id id_clinica, nome, cidade FROM tb_clinica;
CREATE OR REPLACE VIEW TUTOR AS SELECT id id_tutor, nome, cpf, email, telefone FROM tb_tutor;
CREATE OR REPLACE VIEW PET AS SELECT id id_pet, id_tutor, nome,
 CASE especie WHEN 'CACHORRO' THEN 'CAO' ELSE especie END especie, raca,
 CASE sexo WHEN 'MACHO' THEN 'M' WHEN 'FEMEA' THEN 'F' END sexo,
 data_nascimento, peso_kg FROM tb_pet;
CREATE OR REPLACE VIEW ATENDIMENTO AS SELECT id id_atendimento, id_pet, id_clinica,
 veterinario, tipo_consulta servico, data_consulta data_atendimento, valor,
 CASE status WHEN 'CONCLUIDA' THEN 'REALIZADO' WHEN 'CANCELADA' THEN 'CANCELADO'
 WHEN 'AGENDADA' THEN 'AGENDADO' ELSE 'EM_ANDAMENTO' END status FROM tb_consulta;
CREATE TABLE AUD_PET (
 id_auditoria NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_registro NUMBER(19), tipo_operacao VARCHAR2(10) NOT NULL,
 nome_usuario VARCHAR2(128) NOT NULL, data_hora TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 valor_anterior CLOB, valor_novo CLOB);
CREATE OR REPLACE PACKAGE PKG_CLYVOVET AS
 PROCEDURE PRC_ATENDIMENTOS_JSON(p_clinica_id IN NUMBER, p_resultado OUT CLOB);
 PROCEDURE PRC_FATURAMENTO_CLINICA(p_ano IN VARCHAR2, p_resultado OUT CLOB);
 FUNCTION FN_PET_JSON(p_id NUMBER, p_nome VARCHAR2, p_peso NUMBER) RETURN CLOB;
 PROCEDURE PRC_AUDITAR_PET(p_id NUMBER, p_operacao VARCHAR2, p_anterior CLOB, p_novo CLOB);
END PKG_CLYVOVET;
/
CREATE OR REPLACE PACKAGE BODY PKG_CLYVOVET AS
 FUNCTION FN_PET_JSON(p_id NUMBER, p_nome VARCHAR2, p_peso NUMBER) RETURN CLOB IS
  v_json CLOB;
 BEGIN
  SELECT JSON_OBJECT('id' VALUE p_id, 'nome' VALUE p_nome, 'peso_kg' VALUE p_peso RETURNING CLOB)
   INTO v_json FROM dual;
  RETURN v_json;
 END;
 PROCEDURE PRC_AUDITAR_PET(p_id NUMBER, p_operacao VARCHAR2, p_anterior CLOB, p_novo CLOB) IS
 BEGIN
  INSERT INTO AUD_PET(id_registro,tipo_operacao,nome_usuario,valor_anterior,valor_novo)
   VALUES(p_id,p_operacao,USER,p_anterior,p_novo);
 EXCEPTION WHEN OTHERS THEN RAISE_APPLICATION_ERROR(-20051,'Falha ao registrar auditoria do pet');
 END;
 PROCEDURE PRC_ATENDIMENTOS_JSON(p_clinica_id IN NUMBER, p_resultado OUT CLOB) IS
  v_existe NUMBER;
 BEGIN
  IF p_clinica_id IS NOT NULL THEN
   IF p_clinica_id <= 0 THEN RAISE_APPLICATION_ERROR(-20001,'Clinica invalida'); END IF;
   SELECT COUNT(*) INTO v_existe FROM CLINICA WHERE id_clinica=p_clinica_id;
   IF v_existe=0 THEN RAISE_APPLICATION_ERROR(-20002,'Clinica inexistente'); END IF;
  END IF;
  SELECT JSON_ARRAYAGG(JSON_OBJECT(
   'id_atendimento' VALUE a.id_atendimento, 'data' VALUE TO_CHAR(a.data_atendimento,'YYYY-MM-DD'),
   'clinica' VALUE c.nome, 'veterinario' VALUE a.veterinario, 'servico' VALUE a.servico,
   'valor' VALUE a.valor, 'status' VALUE a.status,
   'pet' VALUE JSON_OBJECT('id' VALUE p.id_pet,'nome' VALUE p.nome,'especie' VALUE p.especie),
   'tutor' VALUE JSON_OBJECT('id' VALUE t.id_tutor,'nome' VALUE t.nome)
   RETURNING CLOB) ORDER BY a.id_atendimento RETURNING CLOB)
   INTO p_resultado FROM ATENDIMENTO a JOIN CLINICA c ON c.id_clinica=a.id_clinica
   JOIN PET p ON p.id_pet=a.id_pet JOIN TUTOR t ON t.id_tutor=p.id_tutor
   WHERE p_clinica_id IS NULL OR a.id_clinica=p_clinica_id;
  IF p_resultado IS NULL THEN p_resultado := TO_CLOB('[]'); END IF;
 END;
 PROCEDURE PRC_FATURAMENTO_CLINICA(p_ano IN VARCHAR2, p_resultado OUT CLOB) IS
  v_ano NUMBER; v_total NUMBER:=0; v_subtotal NUMBER:=0; v_clinica NUMBER:=-1;
 BEGIN
  IF NOT REGEXP_LIKE(p_ano,'^[0-9]{4}$') THEN RAISE_APPLICATION_ERROR(-20003,'Ano deve ter quatro digitos'); END IF;
  v_ano:=TO_NUMBER(p_ano);
  IF v_ano < 2000 OR v_ano > 2100 THEN RAISE_APPLICATION_ERROR(-20003,'Ano fora do intervalo 2000-2100'); END IF;
  p_resultado:=TO_CLOB('Faturamento '||p_ano||CHR(10));
  FOR r IN (SELECT a.id_clinica,c.nome,a.servico,a.valor FROM ATENDIMENTO a
    JOIN CLINICA c ON c.id_clinica=a.id_clinica
    WHERE a.status='REALIZADO' AND EXTRACT(YEAR FROM a.data_atendimento)=v_ano
    ORDER BY a.id_clinica,a.servico,a.id_atendimento) LOOP
   IF v_clinica<>r.id_clinica THEN
    IF v_clinica<>-1 THEN p_resultado:=p_resultado||'Subtotal: '||TO_CHAR(v_subtotal,'FM9999999990D00','NLS_NUMERIC_CHARACTERS=''.,''')||CHR(10); END IF;
    v_clinica:=r.id_clinica; v_subtotal:=0;
    p_resultado:=p_resultado||r.nome||CHR(10);
   END IF;
   v_subtotal:=v_subtotal+NVL(r.valor,0); v_total:=v_total+NVL(r.valor,0);
   p_resultado:=p_resultado||'  '||r.servico||': '||TO_CHAR(NVL(r.valor,0),'FM9999999990D00','NLS_NUMERIC_CHARACTERS=''.,''')||CHR(10);
  END LOOP;
  IF v_clinica<>-1 THEN p_resultado:=p_resultado||'Subtotal: '||TO_CHAR(v_subtotal,'FM9999999990D00','NLS_NUMERIC_CHARACTERS=''.,''')||CHR(10); END IF;
  p_resultado:=p_resultado||'Total: '||TO_CHAR(v_total,'FM9999999990D00','NLS_NUMERIC_CHARACTERS=''.,''');
 EXCEPTION WHEN VALUE_ERROR THEN RAISE_APPLICATION_ERROR(-20003,'Ano invalido');
 END;
END PKG_CLYVOVET;
/
CREATE OR REPLACE TRIGGER TRG_AUD_PET AFTER INSERT OR UPDATE OR DELETE ON tb_pet FOR EACH ROW
DECLARE v_op VARCHAR2(10); v_old CLOB; v_new CLOB;
BEGIN
 IF INSERTING THEN v_op:='INSERT'; ELSIF UPDATING THEN v_op:='UPDATE'; ELSE v_op:='DELETE'; END IF;
 IF UPDATING OR DELETING THEN v_old:=PKG_CLYVOVET.FN_PET_JSON(:OLD.id,:OLD.nome,:OLD.peso_kg); END IF;
 IF INSERTING OR UPDATING THEN v_new:=PKG_CLYVOVET.FN_PET_JSON(:NEW.id,:NEW.nome,:NEW.peso_kg); END IF;
 PKG_CLYVOVET.PRC_AUDITAR_PET(COALESCE(:NEW.id,:OLD.id),v_op,v_old,v_new);
END;
/
